-- CurioStar database setup for Supabase
-- Run this entire file in Supabase -> SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'client' check (role in ('client','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.consultations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  dob date,
  tob time,
  pob text,
  question text not null,
  reply text,
  status text not null default 'new' check (status in ('new','replied')),
  created_at timestamptz not null default now(),
  replied_at timestamptz
);

alter table public.profiles enable row level security;
alter table public.consultations enable row level security;

-- Profiles: a signed-in user can read only their own profile.
drop policy if exists "profiles own read" on public.profiles;
create policy "profiles own read" on public.profiles
for select to authenticated using (id = auth.uid());

-- Clients can create and read only their own consultations.
drop policy if exists "consultations own insert" on public.consultations;
create policy "consultations own insert" on public.consultations
for insert to authenticated with check (user_id = auth.uid());

drop policy if exists "consultations own read" on public.consultations;
create policy "consultations own read" on public.consultations
for select to authenticated using (user_id = auth.uid());

-- Admin policies. The admin account is identified by the profiles.role field.
-- IMPORTANT: create the admin user's profile after creating your account.
drop policy if exists "admin all consultations" on public.consultations;
create policy "admin all consultations" on public.consultations
for all to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- Admin can read all profiles if needed.
drop policy if exists "admin profiles read" on public.profiles;
create policy "admin profiles read" on public.profiles
for select to authenticated
using (id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- Automatically create a client profile when a new auth user signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'display_name',''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

